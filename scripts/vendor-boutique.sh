#!/usr/bin/env bash
# Vendor the Online Boutique release manifest (ADR-0007):  scripts/vendor-boutique.sh [tag]
# Writes apps/online-boutique/upstream/{kubernetes-manifests.yaml,SHA256SUMS,kustomization.yaml}. The tag must equal
# versions.env BOUTIQUE_VERSION (update that first when upgrading). Never edit the vendored manifest by hand: all
# changes go into apps/online-boutique/overlays/ (scripts/check-versions.sh verifies the checksum).
set -euo pipefail
# shellcheck source=bootstrap/scripts/lib.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/bootstrap/scripts/lib.sh"
load_env
require_cmd curl sha256sum

TAG=${1:-$BOUTIQUE_VERSION}
[[ "$TAG" == "$BOUTIQUE_VERSION" ]] || die "tag $TAG != versions.env BOUTIQUE_VERSION $BOUTIQUE_VERSION (update versions.env first)"
DEST="$REPO_ROOT/apps/online-boutique/upstream"
URL="https://raw.githubusercontent.com/GoogleCloudPlatform/microservices-demo/${TAG}/release/kubernetes-manifests.yaml"
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

log "downloading $URL"
curl -fsSL --retry 3 -o "$TMP/kubernetes-manifests.yaml" "$URL"
grep -q "${BOUTIQUE_IMAGE_REGISTRY}/frontend:${TAG}" "$TMP/kubernetes-manifests.yaml" ||
  die "downloaded manifest does not reference ${BOUTIQUE_IMAGE_REGISTRY}/frontend:${TAG}"

mkdir -p "$DEST"
install -m 0644 "$TMP/kubernetes-manifests.yaml" "$DEST/kubernetes-manifests.yaml"
(cd "$DEST" && sha256sum kubernetes-manifests.yaml >SHA256SUMS)
cat >"$DEST/kustomization.yaml" <<EOF
# GENERATED by scripts/vendor-boutique.sh (${TAG}) - do not edit. Base for apps/online-boutique/overlays/.
# Source: ${URL}
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - kubernetes-manifests.yaml
EOF
ok "vendored ${TAG}: $(cut -c1-64 "$DEST/SHA256SUMS")"
